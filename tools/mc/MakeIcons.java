import com.nickrocks.pixelflowbot.core.mc.McIcons;
import com.nickrocks.pixelflowbot.core.mc.McLayout;
import com.nickrocks.pixelflowbot.vision.Frame;

import javax.imageio.ImageIO;
import java.awt.image.BufferedImage;
import java.io.File;
import java.io.PrintWriter;

/**
 * Builds McIconData.java from labelled slots in the user's screen recording (tools/mc/samples).
 * Each line: frame, where (r=row,col of the recipe book · h=hotbar slot · o2/o3=output slot), label.
 * Labels starting with "x_" are other recipes, kept only so they are never mistaken for the ones we craft.
 *   java -cp /tmp/mc MakeIcons tools/mc/samples app/src/main/java/com/nickrocks/pixelflowbot/core/mc/McIconData.java
 */
public class MakeIcons {
    static final String[][] LABELS = {
            // 3×3 crafting-table recipe book, with a crafting table in front (frame 128)
            {"128", "r0,1", "x_fence"}, {"128", "r0,2", "x_gate"}, {"128", "r0,3", "x_stairs"}, {"128", "r0,4", "x_door"},
            {"128", "r0,5", "x_trapdoor"}, {"128", "r0,6", "x_ladder"}, {"128", "r1,0", "planks"}, {"128", "r1,1", "x_wood"},
            {"128", "r1,2", "wooden_sword"}, {"128", "r1,3", "x_spear"}, {"128", "r1,4", "wooden_axe"}, {"128", "r1,5", "wooden_pickaxe"},
            {"128", "r1,6", "wooden_shovel"}, {"128", "r2,0", "x_hoe"}, {"128", "r2,1", "stick"}, {"128", "r2,2", "x_torch"},
            {"128", "r2,3", "crafting_table"}, {"128", "r2,4", "x_campfire"}, {"128", "r2,5", "x_barrel"}, {"128", "r2,6", "x_sign"},
            {"128", "r3,0", "button"}, {"128", "r3,1", "x_plate"}, {"128", "r0,0", "planks"},
            // 2×2 inventory recipe book
            {"097", "r0,0", "planks"}, {"097", "r0,1", "x_wood"}, {"097", "r0,2", "stick"}, {"097", "r0,3", "crafting_table"},
            {"097", "r0,4", "button"}, {"097", "r0,5", "x_plate"},
            {"080", "r0,0", "planks"}, {"080", "r0,1", "x_wood"}, {"080", "r0,2", "crafting_table"},
            {"084", "r0,0", "planks"}, {"101", "r0,2", "stick"}, {"112", "r0,3", "x_torch"}, {"112", "r0,4", "crafting_table"},
            // hotbar on the crafting screen
            {"080", "h0", "log"}, {"097", "h0", "planks"}, {"112", "h0", "stick"}, {"112", "h1", "planks"},
            {"112", "h2", "crafting_table"}, {"131", "h0", "wooden_pickaxe"},
            // output slots
            {"084", "o2", "planks"}, {"101", "o2", "stick"}, {"112", "o2", "crafting_table"}, {"131", "o3", "wooden_pickaxe"},
    };

    static float[] where(String w) {
        if (w.startsWith("r")) {
            String[] rc = w.substring(1).split(",");
            return new float[]{McLayout.recipeX(Integer.parseInt(rc[1])), McLayout.recipeY(Integer.parseInt(rc[0]))};
        }
        if (w.startsWith("h")) return new float[]{McLayout.invSlotX(Integer.parseInt(w.substring(1))), McLayout.INV_SLOT_Y};
        if (w.equals("o2")) return new float[]{McLayout.OUT2_X, McLayout.OUT2_Y};
        return new float[]{McLayout.OUT3_X, McLayout.OUT3_Y};
    }

    static Frame load(File f) throws Exception {
        BufferedImage im = ImageIO.read(f);
        int w = im.getWidth(), h = im.getHeight();
        return new Frame(w, h, im.getRGB(0, 0, w, h, null, 0, w));
    }

    public static void main(String[] a) throws Exception {
        File dir = new File(a[0]);
        try (PrintWriter out = new PrintWriter(a[1], "UTF-8")) {
            out.println("package com.nickrocks.pixelflowbot.core.mc;");
            out.println();
            out.println("/** Generated by tools/mc/MakeIcons from the user's screen recording. Do not edit by hand. */");
            out.println("final class McIconData {");
            out.println("    private McIconData() { }");
            out.println();
            out.println("    static final String[][] ICONS = {");
            for (String[] l : LABELS) {
                Frame f = load(new File(dir, "rec_" + l[0] + ".jpg"));
                float[] p = where(l[1]);
                McIcons.Desc d = McIcons.describe(f, p[0], p[1]);
                out.println("            {\"" + l[2] + "\", \"" + McIcons.encode(d) + "\"}, // " + l[0] + " " + l[1]);
            }
            out.println("    };");
            out.println("}");
        }
        System.out.println("wrote " + LABELS.length + " templates");
    }
}
